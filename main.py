def train_one_target(word, initial_vec, teacher_train_rel, student_train_mat,
                     objective="cosine", epochs=EPOCHS, lr=LR, lambda_rank=LAMBDA_RANK):
    """Fixed sampler: randomly sample negatives (not first-K)."""
    vector = nn.Parameter(initial_vec.to(DEVICE).float().clone())
    opt = torch.optim.Adam([vector], lr=lr)
    target_rel = teacher_train_rel.to(DEVICE).float()

    for _ in range(epochs):
        opt.zero_grad()
        pred = F.normalize(vector.float(), dim=0) @ student_train_mat.T
        loss_cos = F.mse_loss(pred, target_rel)
        # ---- pairwise ranking with RANDOM negatives ----
        pos_idx = torch.topk(target_rel, k=min(TOP_K, target_rel.numel())).indices
        neg_mask = torch.ones(target_rel.numel(), dtype=torch.bool, device=DEVICE)
        neg_mask[pos_idx] = False
        neg_idx = torch.where(neg_mask)[0]
        if len(neg_idx) > MAX_PAIRS:
            perm = torch.randperm(len(neg_idx), device=DEVICE)
            neg_idx = neg_idx[perm[:MAX_PAIRS]]
        if len(neg_idx) == 0:
            loss_rank = pred.sum() * 0
        else:
            pos_scores = pred[pos_idx].unsqueeze(1)
            neg_scores = pred[neg_idx].unsqueeze(0)
            loss_rank = F.softplus(RANK_MARGIN - (pos_scores - neg_scores)).mean()
        if objective == "cosine":        loss = loss_cos
        elif objective == "recall_surrogate": loss = loss_rank
        elif objective == "combined":    loss = loss_cos + lambda_rank * loss_rank
        else: raise ValueError(objective)
        loss.backward(); opt.step()
    return vector.detach()

