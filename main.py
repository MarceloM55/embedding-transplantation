def probe_logits(prompt, target_word):
    """Return (target_logit, median_logit, p99_logit, rank) at the last position."""
    ids = student_tokenizer(prompt, return_tensors="pt").to(DEVICE)
    with torch.no_grad():
        out = student(**ids, output_hidden_states=True)
        h = out.hidden_states[-1][0, -1].float()
        W = student.get_output_embeddings().weight.float()
        logits = W @ h
        t_id = target_token_ids[target_word]
        t_logit = logits[t_id].item()
        rank = (logits > t_logit).sum().item() + 1
    return t_logit, logits.median().item(), logits.quantile(0.99).item(), rank

