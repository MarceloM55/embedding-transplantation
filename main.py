@torch.inference_mode()
def teacher_activation_for_text(text):
    captured = {}
    def hook(module, inputs, output):
        out = output[0] if isinstance(output, tuple) else output
        captured["act"] = out.detach()
    handle = teacher_mlp.register_forward_hook(hook)
    try:
        batch = teacher_tokenizer(text, return_tensors="pt", truncation=True,
                                  max_length=MAX_LENGTH).to(DEVICE)
        _ = teacher(**batch, use_cache=False)
        act = captured["act"][0, -1].float().cpu()
    finally:
        handle.remove()
    return act

